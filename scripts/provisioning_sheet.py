#!/usr/bin/env python3
"""
provisioning_sheet.py — what each plugin's Claude.ai installation preference
should be, derived from the catalog rather than remembered.

Claude.ai assignment is a per-plugin console action with no bulk path, and it is
the step docs/GROUP-ONBOARDING.md already flags as the one most likely to be
skipped. When it is skipped, nothing reports it: a published plugin either
reaches nobody, or reaches everybody on a surface where it cannot work.

This does not perform the assignment — there is no admin API for it here, and
the console is the only path. What it does is compute the answer, say why, and
put it somewhere a reviewer sees. Regenerate it on merge and the required
console action shows up in the PR that caused it.

Deliberately refuses to guess where a human decision belongs: which *groups* get
a plugin that does work on Claude.ai is judgement, and inventing an answer there
would be worse than saying so.

Usage:
  python scripts/provisioning_sheet.py                 # markdown to stdout
  python scripts/provisioning_sheet.py --out FILE      # write it
  python scripts/provisioning_sheet.py --check FILE    # fail if FILE is stale
"""
import argparse
import json
import pathlib
import sys

import yaml

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from utils import load_plugins, skill_metadata  # noqa: E402

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")

REPO_ROOT = pathlib.Path(__file__).resolve().parent.parent

# Verdicts, in the order the code decides them.
UNPUBLISHED = "— not published"
NOT_AVAILABLE = "Not available"
HUMAN = "needs a human decision"


def skill_surfaces(plugin_dir: pathlib.Path) -> tuple[int, set[str]]:
    """Return (skill count, the union of surfaces its skills declare)."""
    surfaces: set[str] = set()
    skills = sorted(plugin_dir.rglob("SKILL.md"))
    for s in skills:
        try:
            fm = yaml.safe_load(s.read_text(encoding="utf-8").split("---")[1]) or {}
        except (IndexError, yaml.YAMLError):
            continue  # validate_skill.py reports malformed frontmatter
        raw = skill_metadata(fm).get("surfaces")
        values = ([x.strip() for x in raw.split(",")] if isinstance(raw, str)
                  else [str(x).strip() for x in (raw or [])])
        surfaces |= {v for v in values if v}
    return len(skills), surfaces


def rows(root: pathlib.Path, registered: dict) -> list[dict]:
    out = []
    for manifest in sorted(root.glob("plugins/*/**/.claude-plugin/plugin.json")):
        plugin_dir = manifest.parent.parent
        try:
            name = (json.loads(manifest.read_text(encoding="utf-8")) or {}).get("name")
        except json.JSONDecodeError:
            continue  # validate_skill.py reports this
        if not name:
            continue
        count, surfaces = skill_surfaces(plugin_dir)

        if name not in registered:
            setting = UNPUBLISHED
            why = "not in marketplace.json — invisible on both surfaces"
        elif count == 0:
            setting = NOT_AVAILABLE
            why = "published but has no skills — nothing to install"
        elif "claude-ai" not in surfaces:
            setting = NOT_AVAILABLE
            why = (f"every skill is claude-code only ({', '.join(sorted(surfaces))}) — "
                   "Claude.ai's sandbox cannot see the local filesystem, so it would "
                   "install cleanly and do nothing")
        else:
            setting = HUMAN
            why = "works on Claude.ai — which groups get it is a judgement, not a lookup"
        out.append({
            "plugin": name,
            "path": plugin_dir.relative_to(root).as_posix(),
            "skills": count,
            "setting": setting,
            "why": why,
        })
    return out


def render(data: list[dict]) -> str:
    # Only published plugins get a row. An unpublished one is invisible on both
    # surfaces and needs no console action, so listing it is noise that grows
    # with the catalog while the actionable part does not — and it churns the
    # diff on every merge, which is what stops reviewers reading it.
    published = [r for r in data if r["setting"] != UNPUBLISHED]
    unpublished = [r for r in data if r["setting"] == UNPUBLISHED]

    L = [
        "# Claude.ai provisioning",
        "",
        "Generated by `scripts/provisioning_sheet.py` from each skill's `metadata.surfaces`",
        "field and `.claude-plugin/marketplace.json`. Do not edit by hand.",
        "",
        "Assignment itself is a per-plugin console action —",
        "**Organization settings → Plugins → the plugin's row → Custom access** —",
        "and requires Owner or Primary Owner. This sheet says what to set, not who set it.",
        "",
    ]
    if published:
        L += [
            "| Plugin | Skills | Installation preference | Why |",
            "|---|---|---|---|",
        ]
        for r in published:
            L.append(f"| `{r['plugin']}` | {r['skills']} | **{r['setting']}** | {r['why']} |")
    else:
        L.append("_Nothing is published yet, so there is nothing to set._")

    if unpublished:
        # Named up to a cap, then counted. Naming all of them produced a single
        # 3,000-character line once the catalog reached 200 plugins — the table
        # scaled, this did not. The names are a convenience; the count is the
        # part that matters, since none of them needs an action.
        cap = 10
        shown = ", ".join(f"`{r['plugin']}`" for r in unpublished[:cap])
        rest = len(unpublished) - cap
        tail = f", and {rest} more" if rest > 0 else ""
        L += ["",
              f"{len(unpublished)} plugin(s) are built but not published and need no "
              f"action: {shown}{tail}. They are invisible on both surfaces until they "
              "have an entry in `marketplace.json`."]

    blocked = [r for r in data if r["setting"] == NOT_AVAILABLE and r["skills"]]
    if blocked:
        L += ["", "## Needs setting to Not available", ""]
        for r in blocked:
            L.append(f"- **{r['plugin']}** — {r['why']}")
        L += ["",
              "These are published, so they appear in the Claude.ai catalog when the",
              "marketplace syncs. Left at the default they can be assigned to a group and",
              "will do nothing there."]

    todo = [r for r in data if r["setting"] == HUMAN]
    if todo:
        L += ["", "## Needs a decision", ""]
        for r in todo:
            L.append(f"- **{r['plugin']}** — works on Claude.ai; decide which groups, "
                     "and whether *Available for install* or *Required*.")
    return "\n".join(L) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", metavar="FILE", help="write the sheet here")
    ap.add_argument("--check", metavar="FILE",
                    help="exit 1 if FILE does not match what would be generated")
    args = ap.parse_args()

    text = render(rows(REPO_ROOT, load_plugins()))

    if args.check:
        p = pathlib.Path(args.check)
        current = p.read_text(encoding="utf-8") if p.exists() else ""
        if current != text:
            print(f"{args.check} is out of date — regenerate it:", file=sys.stderr)
            print(f"  python scripts/provisioning_sheet.py --out {args.check}",
                  file=sys.stderr)
            return 1
        print(f"{args.check} is up to date.")
        return 0

    if args.out:
        pathlib.Path(args.out).write_text(text, encoding="utf-8")
        print(f"Wrote {args.out}")
    else:
        sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
